/**
 * Extracts the catalog from the legacy single-file catalog (index.html) and
 * emits src/catalog/products.ts and src/catalog/categories.ts.
 *
 * Run once during the migration. The legacy file is replaced by the Vite entry
 * afterwards, so this script is kept only as a record of where the typed
 * catalog came from. It is not part of the app build.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const html = readFileSync(join(root, 'index.html'), 'utf8');

const start = html.indexOf('var CATS = [');
const end = html.indexOf('\n];', start);
if (start === -1 || end === -1) throw new Error('CATS array not found in index.html');
const block = html.slice(start, end);

const catRe = /\{id:"([^"]+)",name:"([^"]+)",blurb:"([^"]*)",rows:`([\s\S]*?)`\}/g;

const MODELS = new Set(['S', 'O', 'B', 'C']);

function slug(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function tsString(value) {
  return JSON.stringify(value);
}

const categories = [];
const products = [];
const idByName = new Map();
const nameById = new Map();
const unresolvedAlternatives = new Map();

let match;
while ((match = catRe.exec(block)) !== null) {
  const [, catId, catName, blurb, rowsBlock] = match;
  const lines = rowsBlock.trim().split('\n');

  const category = { id: catId, name: catName, blurb, productIds: [] };

  for (const line of lines) {
    const parts = line.split('|');
    if (parts.length < 3) throw new Error(`Bad row in ${catId}: ${line}`);
    const [rawName, model, what, altRaw] = parts;

    if (!MODELS.has(model)) throw new Error(`Unknown model "${model}" in ${catId}: ${rawName}`);

    const id = slug(rawName);
    if (idByName.has(id)) {
      throw new Error(`Slug collision: "${rawName}" and "${nameById.get(id)}" both slug to "${id}"`);
    }

    const alternativeNames = altRaw
      ? altRaw
          .split(',')
          .map((s) => s.trim())
          .filter(Boolean)
      : [];

    const product = {
      id,
      name: rawName,
      model,
      what,
      categoryId: catId,
      alternativeNames,
    };

    products.push(product);
    idByName.set(id, rawName);
    nameById.set(id, rawName);
    category.productIds.push(id);
  }

  categories.push(category);
}

// Resolve alternative names to product ids. Names that are not products in the
// catalog are kept separately so no information is lost.
for (const product of products) {
  const resolved = [];
  const external = [];
  for (const alt of product.alternativeNames) {
    const altId = slug(alt);
    if (idByName.has(altId)) {
      resolved.push(altId);
    } else {
      external.push(alt);
    }
  }
  product.alternatives = resolved;
  product.externalAlternatives = external;
  if (external.length > 0) {
    unresolvedAlternatives.set(product.id, external);
  }
  delete product.alternativeNames;
}

const outDir = join(root, 'src', 'catalog');
mkdirSync(outDir, { recursive: true });

const modelComment = `// Delivery model: S = managed, O = open source, B = open core with hosted version, C = cloud provider service.`;

writeFileSync(
  join(outDir, 'products.ts'),
  `// AUTO-GENERATED by scripts/extract-catalog.mjs. Do not edit by hand.
// Source: the legacy single-file catalog.
${modelComment}

export interface Product {
  id: string;
  name: string;
  model: 'S' | 'O' | 'B' | 'C';
  what: string;
  categoryId: string;
  /** Alternatives that exist in this catalog, as product ids. */
  alternatives: string[];
  /** Alternatives named in the source that are not products here. */
  externalAlternatives: string[];
}

export const PRODUCTS: Product[] = [
${products
  .map(
    (p) =>
      `  { id: ${tsString(p.id)}, name: ${tsString(p.name)}, model: ${tsString(p.model)}, what: ${tsString(p.what)}, categoryId: ${tsString(p.categoryId)}, alternatives: [${p.alternatives
        .map(tsString)
        .join(', ')}], externalAlternatives: [${p.externalAlternatives
        .map(tsString)
        .join(', ')}] },`,
  )
  .join('\n')}
];
`,
);

writeFileSync(
  join(outDir, 'categories.ts'),
  `// AUTO-GENERATED by scripts/extract-catalog.mjs. Do not edit by hand.
// Source: the legacy single-file catalog.

export interface Category {
  id: string;
  name: string;
  blurb: string;
  productIds: string[];
}

export const CATEGORIES: Category[] = [
${categories
  .map(
    (c) =>
      `  { id: ${tsString(c.id)}, name: ${tsString(c.name)}, blurb: ${tsString(c.blurb)}, productIds: [${c.productIds
        .map(tsString)
        .join(', ')}] },`,
  )
  .join('\n')}
];
`,
);

const totalProducts = products.length;
const totalAlternatives = products.reduce((n, p) => n + p.alternatives.length, 0);
console.log(`categories: ${categories.length}`);
console.log(`products: ${totalProducts}`);
console.log(`resolved alternatives: ${totalAlternatives}`);
console.log(`products with external-only alternatives: ${unresolvedAlternatives.size}`);
for (const [id, ext] of unresolvedAlternatives) {
  console.log(`  ${id}: ${ext.join(', ')}`);
}
