/**
 * Language definitions for the code highlighter.
 *
 * Kept as data, separate from the tokenizer, so adding a language is a matter of
 * appending a table entry rather than touching the scanning algorithm.
 */

export interface LanguageSpec {
  /** Token shown in the code block header. */
  label: string;
  /** Line comment prefix, e.g. `#` or `//`. */
  lineComment?: string;
  /** Block comment delimiters. */
  blockComment?: readonly [string, string];
  /** Reserved words. Compared case-sensitively. */
  keywords: ReadonlySet<string>;
  /** Standard-library / runtime names worth a distinct colour. */
  builtins: ReadonlySet<string>;
  /** Treat `identifier:` as a key (YAML). */
  keyColon?: boolean;
  /** Highlight `$NAME` / `$1` as a variable. */
  variables?: boolean;
}

