/** Fall back to plain text rather than guessing at an unknown language. */
export const PLAIN_LANGUAGE: LanguageSpec = {
  label: 'Text',
  keywords: new Set(),
  builtins: new Set(),
};

export function languageFor(lang: string | undefined): LanguageSpec {
  if (!lang) return PLAIN_LANGUAGE;
  return LANGUAGES[lang.toLowerCase()] ?? PLAIN_LANGUAGE;
}
